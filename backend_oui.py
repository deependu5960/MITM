def lookup_vendor(mac):
    if not mac:
        return "Unknown"
    norm = mac.upper().replace("-", ":").strip()
    parts = norm.split(":")
    if len(parts) < 3:
        return "Unknown"
    prefix = ":".join(parts[:3])
    return _OUI.get(prefix, "Unknown")


def is_randomized_mac(mac):
    """Locally-administered bit → MAC is randomized (privacy MAC)."""
    if not mac:
        return False
    try:
        first = int(mac.split(":")[0], 16)
        return bool(first & 0x02)
    except Exception:
        return False